// Conversion helpers
inline constexpr double PA_PER_KPA = 1000.0;
inline constexpr double PA_PER_PSI = 6894.757;
inline constexpr double kpaToPa(double kpa) { return kpa * PA_PER_KPA; }
inline constexpr double paToKpa(double pa) { return pa / PA_PER_KPA; }
inline constexpr double psiToPa(double psi) { return psi * PA_PER_PSI; }
inline constexpr double paToPsi(double pa) { return pa / PA_PER_PSI; }

/**
 * Static physical properties of a pneumatic tyre specification.
 */
struct PneumaticTireProperties {
    // Geometry
    double outerRadius{0.32};        // Nominal unloaded outer radius R_0 (m)
    double rimRadius{0.22};          // Rigid rim / bead radius R_rim (m)
    double sectionWidth{0.24};       // Nominal tread width W_0 (m)
    double sidewallHeight{0.10};     // H_s = R_0 - R_rim (m)
    double carcassMass{12.5};        // Effective rotating mass of rubber carcass (kg)
    double rotationalInertia{0.95};  // Carcass rotational inertia (kg*m^2)

    // Pneumatic Pressure Specification (Pa)
    double nominalPressurePa{220000.0}; // 220 kPa = 31.9 PSI
    double minSafePressurePa{80000.0};   // 80 kPa = 11.6 PSI
    double maxSafePressurePa{360000.0};  // 360 kPa = 52.2 PSI
    double burstPressurePa{550000.0};    // 550 kPa = 79.8 PSI

    // Structural Carcass Stiffness (N/m)
    double radialStiffnessBase{180000.0};          // k_r0 at nominal pressure (N/m)
    double radialStiffnessPressureCoeff{0.48};     // dk_r / dp in N/(m*Pa) -> +48 kN/m per 100 kPa
    double radialDampingCoeff{1500.0};             // c_r structural damping (N*s/m)

    double lateralStiffnessBase{140000.0};         // k_y0 cornering carcass stiffness (N/m)
    double lateralStiffnessPressureCoeff{0.32};    // dk_y / dp
    double lateralDampingCoeff{950.0};             // c_y lateral damping (N*s/m)

    double longitudinalStiffnessBase{190000.0};    // k_x0 traction/braking carcass stiffness (N/m)
    double longitudinalStiffnessPressureCoeff{0.36}; // dk_x / dp
    double longitudinalDampingCoeff{1100.0};       // c_x longitudinal damping (N*s/m)

    // Elastomer Mechanics
    double poissonRatio{0.45};       // Rubber Poisson ratio nu (sidewall outward bulge factor)
    double hysteresisLossFraction{0.035}; // Energy loss per deformation cycle converted to heat

    // Thermal Properties
    double thermalMass{14500.0};      // Heat capacity C_th (J/K)
    double ambientTempC{25.0};        // Ambient temperature (deg C)
    double optimalTempC{85.0};        // Peak grip temperature (deg C)
    double tempGripHalfWidthC{30.0};  // Temperature sensitivity range (deg C)
    double heatTransferAirBase{18.0}; // Still air heat transfer coefficient (W/K)
    double heatTransferAirSpeed{1.8}; // Convective heat transfer per m/s speed (W/(K*(m/s)))
    double heatTransferRoad{32.0};    // Conduction heat transfer to pavement (W/K)

    // Wear Model
    double wearRatePerJoule{1.2e-8};  // Tread volume wear index per Joule of sliding work
};

/**
 * Individual contact patch sample point in a distributed contact representation.
 */
struct TireContactPointSample {
    int index{0};
    double normalizedU{0.0};         // [-1..+1] Longitudinal position along contact patch (+ = forward, - = rear)
    double normalizedV{0.0};         // [-1..+1] Lateral position across tread width (+ = left, - = right)

    Vec3 undeformedPosWorld{0.0, 0.0, 0.0}; // Point on rigid cylindrical reference surface
    Vec3 contactPointWorld{0.0, 0.0, 0.0};  // Actual point of contact on ground/obstacle
    Vec3 contactNormalWorld{0.0, 1.0, 0.0}; // Ground/obstacle reaction unit normal
    double penetrationDepth{0.0};            // Local vertical deformation delta_rj (m, >= 0)
    double penetrationVelocity{0.0};         // Rate of penetration change (m/s)

    bool inContact{false};
    double normalLoad{0.0};                  // Vertical force F_zj contributed by this sample (N)
    double longitudinalSlip{0.0};            // Local longitudinal slip kappa_j
    double lateralSlip{0.0};                 // Local lateral slip alpha_j (rad)
    double longitudinalForce{0.0};           // Tangential force F_xj (N, +forward)
    double lateralForce{0.0};                // Tangential force F_yj (N, +left)
    double frictionCoeff{0.0};               // Local load-sensitive friction coefficient mu_j
    double slidingVelocityMps{0.0};          // Sliding speed on ground (m/s)
    double frictionalPowerWatts{0.0};        // Local heating rate (W)
};

/**
 * Dynamic state of a pneumatic tyre during simulation.
 */
struct PneumaticTireState {
    // Current pneumatic state
    double pressurePa{220000.0};     // Current internal pressure p (Pa)
    double nominalPressurePa{220000.0}; // Reference cold pressure (Pa)
    double temperatureC{25.0};       // Bulk tread and carcass temperature (deg C)
    double wearLevel{0.0};           // Normalized tread wear [0 = fresh, 1 = bald]
    double damageLevel{0.0};         // Normalized structural carcass damage [0 = intact, 1 = destroyed]
    double punctureRatePaPerSec{0.0};// Active pressure leakage rate (Pa/s)
    bool isPunctured{false};
    bool isBlown{false};

    // Effective structural stiffnesses at current pressure p
    double radialStiffness{230000.0};       // k_r(p) (N/m)
    double lateralStiffness{175000.0};      // k_y(p) (N/m)
    double longitudinalStiffness{235000.0}; // k_x(p) (N/m)

    // Current physical deformations (SI meters)
    double radialDeformation{0.0};          // delta_r: vertical radial squash at bottom contact patch (m, >= 0)
    double radialDeformationVelocity{0.0};  // d(delta_r)/dt (m/s)
    double lateralDeformation{0.0};         // delta_y: carcass lateral deflection under cornering load (m)
    double lateralDeformationVelocity{0.0}; // d(delta_y)/dt (m/s)
    double longitudinalDeformation{0.0};    // delta_x: carcass longitudinal shear under drive/braking torque (m)
    double sidewallBulge{0.0};              // delta_w: outward sidewall expansion near contact patch (m)
    double effectiveRadius{0.32};           // R_eff = R_0 - 0.33 * delta_r (rolling kinematic radius)

    // Geometry of the contact patch
    double contactPatchLength{0.0};         // 2*a: longitudinal length of footprint (m)
    double contactPatchWidth{0.24};         // 2*b: lateral width of footprint (m)
    double contactPatchArea{0.0};           // Footprint area A_p (m^2)
    double meanContactPressurePa{0.0};      // F_z / A_p (Pa)
    int activeContactSamples{0};            // Count of active contact points on ground
    int totalContactSamples{9};             // Total sample resolution

    // Distributed Contact Samples (Circumferential x Lateral)
    std::vector<TireContactPointSample> contactSamples;

    // Aggregated Contact Patch Forces & Torques
    double totalNormalLoad{0.0};            // F_z = sum(F_zj) (N)
    double totalLongitudinalForce{0.0};     // F_x = sum(F_xj) (N)
    double totalLateralForce{0.0};          // F_y = sum(F_yj) (N)
    double selfAligningTorque{0.0};         // M_z from pneumatic trail and distributed shear (N*m)
    double rollingResistanceTorque{0.0};    // M_rr from asymmetric pressure distribution (N*m)
    Vec3 contactCentroidWorld{0.0, 0.0, 0.0}; // Geometric center of the contact patch (m)
    Vec3 netContactForceWorld{0.0, 0.0, 0.0}; // Net 3D force vector applied to chassis/wheel (N)

    // Thermodynamic & Wear Metrics
    double thermalGripMultiplier{1.0};      // Grip scaling factor mu(T) [0.70 .. 1.05]
    double totalFrictionalPowerWatts{0.0};  // Instantaneous sliding power (W)
    double totalFlexurePowerWatts{0.0};     // Instantaneous structural hysteresis heating (W)
};

/**
 * Physically based pneumatic tyre simulation engine.
 */
class PneumaticTireModel {
public:
    PneumaticTireModel() = default;
    explicit PneumaticTireModel(const PneumaticTireProperties& props);

    /** Resets the tyre state to fresh nominal conditions. */
    void reset(double initialPressurePa = 220000.0, double initialTempC = 25.0);

    /** Updates internal pressure and dynamic stiffness based on pressure and leakage. */
    void updatePneumaticState(double dt);

    /**
     * Updates thermal thermodynamics: frictional sliding heat + hysteresis flexure heating
     * balanced by convective air cooling and road conduction.
     */
    void updateThermodynamics(double dt, double vehicleSpeedMps);

    /** Updates tread wear accumulation from frictional work. */
    void updateWear(double dt);

    /** Sets target pressure (e.g. from user UI or air compressor). */
    void setTargetPressure(double pressurePa);

    /** Triggers or repairs a puncture. */
    void setPunctured(bool punctured, double leakRatePaPerSec = 4500.0);

    /** Calculates pressure-dependent radial stiffness k_r(p). */
    double computeRadialStiffness(double p) const;

    /** Calculates pressure-dependent lateral stiffness k_y(p). */
    double computeLateralStiffness(double p) const;

    /** Calculates pressure-dependent longitudinal stiffness k_x(p). */
    double computeLongitudinalStiffness(double p) const;

    /** Calculates contact patch dimensions from normal load and pressure. */
    void computeContactPatchDimensions(double normalLoad, double& outLength, double& outWidth) const;

    /** Computes thermal grip multiplier based on current temperature. */
    double computeThermalGripFactor(double tempC) const;

    /**
     * Evaluates multi-point distributed tyre contact and deformation against the environment.
     * Integrates Kelvin-Voigt structural compliance, distributes contact queries,
     * aggregates forces, and updates radial, lateral, and longitudinal deformation.
     */
    void evaluateDistributedContact(
        double dt,
        double normalLoadRequested,
        double rawSuspensionTravel,
        double wheelAngularVelocity,
        const Vec3& hubCenterWorld,
        const Quat& wheelWorldOrientation,
        const VehicleBasis& steeredBasis,
        const Vec3& chassisDown,
        const SurfaceProperties& surface,
        WheelCollisionFidelity fidelity,
        const std::vector<std::pair<double, double>>& contactHitPoints, // (effectiveSuspLength, hitAngle)
        double chassisVx,
        double chassisVy
    );

    // Accessors
    const PneumaticTireProperties& getProperties() const { return m_props; }
    PneumaticTireProperties& getProperties() { return m_props; }
    const PneumaticTireState& getState() const { return m_state; }
    PneumaticTireState& getState() { return m_state; }

    void setProperties(const PneumaticTireProperties& props) {
        m_props = props;
        updateDynamicStiffness();
    }

private:
    void updateDynamicStiffness();
    void buildSampleGrid(WheelCollisionFidelity fidelity);

    PneumaticTireProperties m_props{};
    PneumaticTireState m_state{};
};

/**
 * Creates default factory tyre properties matching a sports coupe / muscle car fitment.
 */
inline PneumaticTireProperties createDefaultTireProperties(
    double outerRadius = 0.32,
    double sectionWidth = 0.24,
    double rimRadius = 0.22,
    double nominalPressureKpa = 220.0
) {
    PneumaticTireProperties p{};
    p.outerRadius = outerRadius;
    p.sectionWidth = sectionWidth;
    p.rimRadius = rimRadius;
    p.sidewallHeight = std::max(0.04, outerRadius - rimRadius);
    p.nominalPressurePa = kpaToPa(nominalPressureKpa);
    p.radialStiffnessBase = 180000.0;
    p.radialStiffnessPressureCoeff = 0.48;
    p.lateralStiffnessBase = 140000.0;
    p.lateralStiffnessPressureCoeff = 0.32;
    p.longitudinalStiffnessBase = 190000.0;
    p.longitudinalStiffnessPressureCoeff = 0.36;
    return p;
}

