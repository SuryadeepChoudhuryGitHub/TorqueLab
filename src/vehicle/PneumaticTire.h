#pragma once
/**
 * Torque Lab Native — Physically Based Deformable Pneumatic Tyre Simulation.
 *
 * Implements a comprehensive structural, pneumatic, and thermodynamic tyre model:
 * 1. Internal pneumatic pressure p (Pa, kPa, PSI) with pressure-dependent radial,
 *    lateral, and longitudinal carcass stiffnesses:
 *      k_r(p) = k_r0 + c_pr * (p - p0)
 *      k_y(p) = k_y0 + c_py * (p - p0)
 *      k_x(p) = k_x0 + c_px * (p - p0)
 * 2. Viscoelastic Kelvin-Voigt structural damping:
 *      F_r = k_r * delta_r + c_r * delta_r_dot
 * 3. Multi-point distributed contact patch sampling:
 *      Discretized 2D grid across contact length and tread width (circumferential x lateral)
 *      Distributed normal load, local penetration, and shear forces (Fx, Fy)
 *      Self-aligning torque M_z generated by pneumatic trail t_p
 * 4. Carcass & sidewall deformations:
 *      Radial compression delta_r (ground flattening)
 *      Sidewall outward bulge delta_w = nu * delta_r (Poisson ratio volume expansion)
 *      Lateral carcass deflection delta_y = F_y / k_y (cornering lean)
 *      Longitudinal carcass shear delta_x = F_x / k_x (acceleration / braking windup)
 * 5. Tyre thermodynamics & wear:
 *      Heat generation from frictional sliding work and cyclic hysteresis flexure
 *      Cooling via forced convection (vehicle speed) and conduction to pavement
 *      Archard/Pacejka frictional work wear accumulation
 * 6. Damage & pressure loss (puncture leakage and blow-out limits)
 * 7. Rigid rim protection: strict radial threshold ensuring rim geometry never deforms
 */

